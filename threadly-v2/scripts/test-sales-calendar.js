const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..', 'public');
const data = fs.readFileSync(path.join(root, 'sales-data.js'), 'utf8');
const page = fs.readFileSync(path.join(root, 'sales.html'), 'utf8');
const home = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const app = fs.readFileSync(path.join(root, 'sales.js'), 'utf8');
const ids = Array.from(data.matchAll(/id:"([^"]+)"/g), m => m[1]);
const starts = Array.from(data.matchAll(/start:"([^"]+)"/g), m => Date.parse(m[1]));
const ends = Array.from(data.matchAll(/end:"([^"]+)"/g), m => Date.parse(m[1]));
assert.ok(ids.length >= 10, 'expected a full-year calendar');
assert.equal(new Set(ids).size, ids.length, 'campaign IDs must be unique');
assert.equal(starts.length, ids.length);
assert.equal(ends.length, ids.length);
starts.forEach((start, i) => {
  assert.ok(Number.isFinite(start), ids[i] + ' has an invalid start date');
  assert.ok(Number.isFinite(ends[i]), ids[i] + ' has an invalid end date');
  assert.ok(ends[i] > start, ids[i] + ' must end after it starts');
});
assert.match(page, /id="featured"/);
assert.match(page, /id="sale-list"/);
assert.match(page, /id="sale-filter"/);
assert.match(page, /\/sales-data\.js/);
assert.match(page, /\/sales\.js/);
assert.match(home, /href="\/sales\.html"/, 'homepage must link to the sale calendar');
assert.match(home, /id="juno-home-sale"/, 'homepage campaign teaser must be present');
assert.match(app, /Asia\/Kolkata/, 'countdown dates must display in India time');
assert.match(data, /Juno Pink Friday/);
assert.match(data, /Juno Fresh Start Sale/);
console.log('Juno sale calendar tests passed (' + ids.length + ' campaigns).');
